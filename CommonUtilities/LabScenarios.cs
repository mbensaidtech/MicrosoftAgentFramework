using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace CommonUtilities;

/// <summary>
/// One scenario of a lab: a <c>#region Scenario N: Title</c> block of its Program.cs.
/// A <c>// Requires scenario N</c> comment in the block declares a scenario it needs in the same run.
/// <see cref="Fingerprint"/> identifies the code of the block, comments and white space ignored: the scenario is not implemented
/// while that code, or the code before the first scenario (the setup), is still the code of the exercise as delivered
/// (<see cref="DeliveredExercise"/>). Comments never count: removing or keeping a TODO changes nothing.
/// </summary>
public sealed record LabScenario(int Number, string Title, IReadOnlyList<int> Requires)
{
    public string Fingerprint { get; init; } = "";

    /// <summary>The code before the first scenario is no longer the delivered one (always true without a delivered exercise to compare to).</summary>
    public bool SetupImplemented { get; init; } = true;

    /// <summary>The code of the scenario is no longer the delivered one, or the delivered one was already complete (provided scenario).</summary>
    public bool CodeImplemented { get; init; } = true;

    public bool Implemented => SetupImplemented && CodeImplemented;
}

/// <summary>What a run asks for: scenario numbers, every scenario (<see cref="All"/>), or neither: the implemented scenarios.</summary>
public sealed record ScenarioRequest(IReadOnlyList<int>? Numbers, bool All = false)
{
    public static readonly ScenarioRequest Implemented = new(Numbers: null);
}

/// <summary>
/// The scenarios a run executes (<see cref="Selected"/>, ascending), with the scenarios added because a selected one requires them,
/// the selected scenarios that are not implemented, the requested numbers the lab does not have, and the scenarios left out by default.
/// </summary>
public sealed record ScenarioPlan(
    IReadOnlyList<int> Selected,
    IReadOnlyList<int> AddedAsRequired,
    IReadOnlyList<int> NotImplemented,
    IReadOnlyList<int> Unknown,
    IReadOnlyList<int> LeftOut);

/// <summary>The fingerprint of a part of the delivered exercise, and whether the solution has the same code (nothing to write there).</summary>
public sealed record DeliveredPart(string Fingerprint, bool Provided);

/// <summary>
/// The fingerprints of the exercise as delivered (Start/Program.cs), stored next to the Start and Solution folders of the lab
/// (<see cref="LabScenarios.FingerprintFile"/>) and generated from them by the dashboard (<c>dotnet run --project Dashboard/LabDashboard -- exercise-fingerprints</c>).
/// </summary>
public sealed record DeliveredExercise(DeliveredPart Setup, IReadOnlyDictionary<int, DeliveredPart> Scenarios)
{
    public string Note { get; init; } =
        "Fingerprints of the code of the exercise as delivered (Start/Program.cs, comments and white space ignored): a scenario whose code " +
        "is still the delivered one is not implemented yet. Generated by: dotnet run --project Dashboard/LabDashboard -- exercise-fingerprints";
}

/// <summary>
/// The scenario selection rules, shared by the labs (<see cref="ScenarioSelection"/>) and the Lab Bench dashboard (which compiles this file too):
/// the same reading of Program.cs, the same command-line option, the same default and the same lines printed when a scenario starts.
/// </summary>
public static partial class LabScenarios
{
    public const string ScenariosOption = "--scenarios";
    public const string ScenarioOption = "--scenario";
    public const string ListOption = "--list-scenarios";
    public const string AllValue = "all";
    public const string ImplementedValue = "implemented";

    /// <summary>The fingerprints of the delivered exercise, in the folder of the lab (the parent of Start/ and Solution/).</summary>
    public const string FingerprintFile = "exercise-fingerprints.json";

    /// <summary>Start of the line printed when a scenario starts: the dashboard reads it to attach the results and errors to the scenario.</summary>
    public const string MarkerPrefix = ">>> Running scenario ";

    /// <summary>Start of the line printed once, before the first scenario: what runs and what is left out.</summary>
    public const string PlanPrefix = ">>> Scenarios";

    private static readonly JsonSerializerOptions FingerprintJson = new(JsonSerializerDefaults.Web) { WriteIndented = true };

    [GeneratedRegex(@"^\s*#region\s+Scenario\s+(?<number>\d+)\s*:\s*(?<title>.*?)\s*$")]
    private static partial Regex ScenarioRegion();

    [GeneratedRegex(@"^\s*#(?<kind>region|endregion)\b")]
    private static partial Regex RegionBoundary();

    [GeneratedRegex(@"^\s*//\s*Requires scenarios?\s+(?<numbers>\d+(?:\s*(?:,|and)\s*\d+)*)", RegexOptions.IgnoreCase)]
    private static partial Regex RequiresComment();

    [GeneratedRegex(@"^>>> Running scenario (?<number>\d+)\b")]
    private static partial Regex Marker();

    /// <summary>The scenarios declared in a Program.cs, in the order of the file (a number declared twice is kept once).</summary>
    public static IReadOnlyList<LabScenario> Parse(string source, DeliveredExercise? delivered = null)
    {
        (string setup, IReadOnlyList<LabScenario> scenarios) = ParseProgram(source);
        if (delivered is null)
        {
            return scenarios;
        }

        bool setupImplemented = delivered.Setup.Provided || setup != delivered.Setup.Fingerprint;
        return scenarios.Select(scenario => scenario with
        {
            SetupImplemented = setupImplemented,
            // A scenario the exercise did not deliver (added by the learner) is the learner's code.
            CodeImplemented = !delivered.Scenarios.TryGetValue(scenario.Number, out DeliveredPart? part)
                || part.Provided || scenario.Fingerprint != part.Fingerprint,
        }).ToList();
    }

    /// <summary>
    /// The scenarios of a Program.cs file, compared with the delivered exercise of the lab when it has one
    /// (<see cref="FingerprintFile"/> in the parent folder of the project); none when the file cannot be read.
    /// </summary>
    public static IReadOnlyList<LabScenario> ReadFile(string? path)
    {
        try
        {
            if (string.IsNullOrEmpty(path) || !File.Exists(path))
            {
                return [];
            }

            string? labDirectory = Path.GetDirectoryName(Path.GetDirectoryName(Path.GetFullPath(path)));
            string fingerprints = labDirectory is null ? "" : Path.Combine(labDirectory, FingerprintFile);
            DeliveredExercise? delivered = File.Exists(fingerprints) ? ReadDelivered(File.ReadAllText(fingerprints)) : null;
            return Parse(File.ReadAllText(path), delivered);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or JsonException)
        {
            return [];
        }
    }

    /// <summary>The fingerprints of an exercise as delivered (<paramref name="start"/>), the parts identical in the solution being provided.</summary>
    public static DeliveredExercise CreateDelivered(string start, string solution)
    {
        (string startSetup, IReadOnlyList<LabScenario> startScenarios) = ParseProgram(start);
        (string solutionSetup, IReadOnlyList<LabScenario> solutionScenarios) = ParseProgram(solution);
        return new DeliveredExercise(
            new DeliveredPart(startSetup, startSetup == solutionSetup),
            startScenarios.ToDictionary(
                s => s.Number,
                s => new DeliveredPart(s.Fingerprint, solutionScenarios.Any(o => o.Number == s.Number && o.Fingerprint == s.Fingerprint))));
    }

    public static string WriteDelivered(DeliveredExercise delivered) => JsonSerializer.Serialize(delivered, FingerprintJson) + "\n";

    public static DeliveredExercise? ReadDelivered(string json) => JsonSerializer.Deserialize<DeliveredExercise>(json, FingerprintJson);

    /// <summary>The fingerprint of the setup (the code before the first scenario) and the scenarios, each with the fingerprint of its block.</summary>
    private static (string Setup, IReadOnlyList<LabScenario> Scenarios) ParseProgram(string source)
    {
        string[] lines = source.ReplaceLineEndings("\n").Split('\n');
        int firstScenario = Array.FindIndex(lines, line => ScenarioRegion().IsMatch(line));
        string setup = Fingerprint(lines.Take(firstScenario < 0 ? lines.Length : firstScenario));
        List<LabScenario> scenarios = [];
        for (int i = 0; i < lines.Length; i++)
        {
            Match region = ScenarioRegion().Match(lines[i]);
            if (!region.Success || !int.TryParse(region.Groups["number"].Value, out int number))
            {
                continue;
            }

            List<string> body = [];
            List<int> requires = [];
            int depth = 0;
            for (i++; i < lines.Length; i++)
            {
                if (RegionBoundary().Match(lines[i]) is { Success: true } boundary)
                {
                    if (boundary.Groups["kind"].Value == "region")
                    {
                        depth++;
                    }
                    else if (depth-- == 0)
                    {
                        break;
                    }
                }

                body.Add(lines[i]);
                if (RequiresComment().Match(lines[i]) is { Success: true } comment)
                {
                    requires.AddRange(Regex.Matches(comment.Groups["numbers"].Value, @"\d+").Select(m => int.Parse(m.Value)));
                }
            }

            if (scenarios.All(s => s.Number != number))
            {
                scenarios.Add(new LabScenario(number, region.Groups["title"].Value, requires.Where(r => r != number).Distinct().Order().ToList())
                {
                    Fingerprint = Fingerprint(body),
                });
            }
        }

        return (setup, scenarios);
    }

    /// <summary>
    /// Identifies code, not its presentation: comment lines, region lines and white space are left out, so that the fingerprint
    /// changes when code is written, never when a comment (a TODO, a hint) is removed or the code is re-indented.
    /// </summary>
    private static string Fingerprint(IEnumerable<string> lines)
    {
        StringBuilder code = new();
        bool inBlockComment = false;
        foreach (string raw in lines)
        {
            string line = raw.Trim();
            if (inBlockComment)
            {
                inBlockComment = !line.Contains("*/", StringComparison.Ordinal);
                continue;
            }

            if (line.StartsWith("/*", StringComparison.Ordinal))
            {
                inBlockComment = !line.Contains("*/", StringComparison.Ordinal);
                continue;
            }

            if (line.Length == 0 || line.StartsWith("//", StringComparison.Ordinal) || RegionBoundary().IsMatch(line))
            {
                continue;
            }

            foreach (char c in line)
            {
                if (!char.IsWhiteSpace(c))
                {
                    code.Append(c);
                }
            }

            code.Append('\n');
        }

        return Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(code.ToString())))[..16];
    }

    /// <summary>
    /// Reads <c>--scenarios 1,3</c>, <c>--scenarios=1,3</c>, <c>--scenario 2</c>, <c>--scenarios all</c>, <c>--scenarios implemented</c>
    /// and <c>--list-scenarios</c>; every other argument belongs to the lab and is ignored.
    /// </summary>
    public static ScenarioRequest ParseArguments(IReadOnlyList<string> args, out bool list, out string? error)
    {
        list = false;
        error = null;
        List<int>? numbers = null;
        bool all = false;
        for (int i = 0; i < args.Count; i++)
        {
            string arg = args[i];
            if (arg == ListOption)
            {
                list = true;
                continue;
            }

            string? option = arg == ScenariosOption || arg.StartsWith(ScenariosOption + "=", StringComparison.Ordinal) ? ScenariosOption
                : arg == ScenarioOption || arg.StartsWith(ScenarioOption + "=", StringComparison.Ordinal) ? ScenarioOption
                : null;
            if (option is null)
            {
                continue;
            }

            string? value = arg.Length > option.Length ? arg[(option.Length + 1)..] : i + 1 < args.Count ? args[++i] : null;
            if (string.IsNullOrWhiteSpace(value))
            {
                error = $"{option} needs a value: scenario numbers (1,3), '{AllValue}' or '{ImplementedValue}'.";
                return ScenarioRequest.Implemented;
            }

            value = value.Trim();
            if (value.Equals(AllValue, StringComparison.OrdinalIgnoreCase))
            {
                all = true;
                continue;
            }

            if (value.Equals(ImplementedValue, StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            foreach (string part in value.Split([',', ';', ' '], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
            {
                if (!int.TryParse(part, out int number) || number <= 0)
                {
                    error = $"'{part}' is not a scenario number. Use for example {ScenariosOption} 1,3 ({AllValue}: every scenario).";
                    return ScenarioRequest.Implemented;
                }

                (numbers ??= []).Add(number);
            }
        }

        return all ? new ScenarioRequest(null, All: true) : new ScenarioRequest(numbers?.Distinct().Order().ToList());
    }

    /// <summary>The arguments that select these scenarios, after <c>dotnet run ... --</c>.</summary>
    public static IReadOnlyList<string> FormatArguments(IEnumerable<int> numbers) => [ScenariosOption, string.Join(',', numbers)];

    /// <summary>
    /// Decides what runs. Requested numbers run with the scenarios they require (even when one is not implemented: it was asked for);
    /// <see cref="ScenarioRequest.All"/> runs every scenario; otherwise only the implemented scenarios whose required scenarios are implemented too.
    /// When the scenarios of the lab are unknown (no Program.cs), the requested numbers are taken as they are.
    /// </summary>
    public static ScenarioPlan Plan(IReadOnlyList<LabScenario> scenarios, ScenarioRequest request)
    {
        Dictionary<int, LabScenario> known = scenarios.ToDictionary(s => s.Number);
        if (known.Count == 0)
        {
            return new ScenarioPlan(request.Numbers ?? [], [], [], [], []);
        }

        List<int> unknown = request.Numbers?.Where(n => !known.ContainsKey(n)).ToList() ?? [];
        IEnumerable<int> wanted = request.All ? known.Keys
            : request.Numbers is not null ? request.Numbers.Where(known.ContainsKey)
            : known.Values.Where(s => WithRequired([s.Number], known).All(n => known[n].Implemented)).Select(s => s.Number);

        List<int> asked = wanted.ToList();
        List<int> selected = WithRequired(asked, known).Order().ToList();
        return new ScenarioPlan(
            selected,
            selected.Except(asked).ToList(),
            selected.Where(n => !known[n].Implemented).ToList(),
            unknown,
            known.Keys.Except(selected).Order().ToList());
    }

    /// <summary>The scenarios and, transitively, the scenarios they require (only those of the lab).</summary>
    private static HashSet<int> WithRequired(IEnumerable<int> numbers, IReadOnlyDictionary<int, LabScenario> known)
    {
        HashSet<int> result = [];
        Stack<int> pending = new(numbers);
        while (pending.TryPop(out int number))
        {
            if (known.TryGetValue(number, out LabScenario? scenario) && result.Add(number))
            {
                foreach (int required in scenario.Requires)
                {
                    pending.Push(required);
                }
            }
        }

        return result;
    }

    public static string FormatMarker(LabScenario scenario) => $"{MarkerPrefix}{scenario.Number}: {scenario.Title}";

    public static bool TryParseMarker(string line, out int number)
    {
        Match match = Marker().Match(line);
        number = match.Success ? int.Parse(match.Groups["number"].Value) : 0;
        return match.Success;
    }

    /// <summary>A line printed by the scenario selection itself, not by the lab (the dashboard checks the output without them).</summary>
    public static bool IsSelectionLine(string line) =>
        line.StartsWith(MarkerPrefix, StringComparison.Ordinal) || line.StartsWith(PlanPrefix, StringComparison.Ordinal);

    /// <summary>The lines printed before the first scenario: what runs, and why the other scenarios do not.</summary>
    public static IReadOnlyList<string> DescribePlan(IReadOnlyList<LabScenario> scenarios, ScenarioRequest request, ScenarioPlan plan)
    {
        if (scenarios.Count == 0)
        {
            return [];
        }

        string how = request.All ? $"{ScenariosOption} {AllValue}"
            : request.Numbers is not null ? $"{ScenariosOption} {string.Join(',', request.Numbers)}"
            : "the implemented ones";
        List<string> lines = [plan.Selected.Count == 0
            ? $"{PlanPrefix} to run: none ({how})"
            : $"{PlanPrefix} to run: {string.Join(", ", plan.Selected)} ({how}{(plan.AddedAsRequired.Count > 0 ? $"; required: {string.Join(", ", plan.AddedAsRequired)}" : "")})"];

        if (plan.NotImplemented.Count > 0)
        {
            lines.Add($"{PlanPrefix} not implemented yet (code unchanged since the exercise was delivered), run anyway: {string.Join(", ", plan.NotImplemented)}");
        }

        List<int> notImplemented = plan.LeftOut.Where(n => scenarios.First(s => s.Number == n) is { Implemented: false }).ToList();
        if (request.Numbers is null && !request.All && notImplemented.Count > 0)
        {
            string why = scenarios[0].SetupImplemented ? "their code is still the delivered one" : "the setup before the scenarios is still the delivered one";
            lines.Add($"{PlanPrefix} not run: {string.Join(", ", plan.LeftOut)} (not implemented: {why}). " +
                      $"Run one anyway with: dotnet run -- {ScenariosOption} {notImplemented[0]}");
        }

        return lines;
    }

    /// <summary>The answer to <c>--list-scenarios</c>.</summary>
    public static IReadOnlyList<string> Describe(IReadOnlyList<LabScenario> scenarios)
    {
        if (scenarios.Count == 0)
        {
            return ["This program declares no scenario (#region Scenario N: ...)."];
        }

        ScenarioPlan byDefault = Plan(scenarios, ScenarioRequest.Implemented);
        int width = scenarios.Max(s => s.Title.Length);
        List<string> lines = ["Scenarios of this lab:"];
        if (!scenarios[0].SetupImplemented)
        {
            lines.Add("  The code before the scenarios (setup) is still the delivered one: write it first.");
        }

        foreach (LabScenario scenario in scenarios)
        {
            string state = scenario.Implemented ? "implemented"
                : scenario.CodeImplemented ? "not implemented (setup to write)"
                : "not implemented (code unchanged since delivered)";
            string requires = scenario.Requires.Count > 0 ? $", requires {string.Join(", ", scenario.Requires)}" : "";
            lines.Add($"  {scenario.Number,2}  {scenario.Title.PadRight(width)}  {state}{requires}");
        }

        lines.Add("");
        foreach ((string command, string effect) in new[]
        {
            ("dotnet run", $"runs {(byDefault.Selected.Count > 0 ? string.Join(", ", byDefault.Selected) : "no scenario")} (the implemented scenarios)"),
            ($"dotnet run -- {ScenariosOption} 1,3", "runs scenarios 1 and 3 (and the scenarios they require)"),
            ($"dotnet run -- {ScenariosOption} {AllValue}", "runs every scenario, implemented or not"),
        })
        {
            lines.Add($"{command,-32} {effect}");
        }

        return lines;
    }
}
